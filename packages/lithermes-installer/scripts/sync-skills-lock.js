#!/usr/bin/env node
// Writes skills.lock.json at the package root: per bundled skill its SKILL.md size and hash, file count, total
// bytes and one hash over every tracked file, plus the `npm pack --dry-run --json --ignore-scripts` file list.
//
// It does not replace payload-version.json. That manifest stays the authority for payload integrity (the doctor
// and installer verify it); this lock holds what a reviewer decides: how small or large each skill may be, and
// exactly which files the tarball ships.
//
// `policy` and `budgets` are hand-owned and kept as written by every sync. A skill without a budget, or a budget
// whose skill is gone, blocks the write until it is named: `--accept-new <id>` seeds one budget from today's size,
// `--drop <id>` removes one (both repeatable). Any violation writes nothing and exits 1. `--check` never writes.
// Raise a budget by hand when a skill grows on purpose; lower a floor only by hand, in the commit that explains why.
"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { spawnTool, describeSpawnFailure } = require("../src/lib/hostExec");

const packageRoot = path.resolve(__dirname, "..");
const LOCK_PATH = path.join(packageRoot, "skills.lock.json");
const SKILLS_DIR = path.join(packageRoot, "assets", "lithermes-plugin", "skills");
const NOTE =
  "Generated by npm run sync:lock (scripts/sync-skills-lock.js): skills and pack. " +
  "Hand-owned and kept by every sync: policy and budgets. Payload integrity stays in payload-version.json.";
const HEADROOM = 1.5;
// Same escape as payload-version.json: the tracked-token scanner reads raw text, and one packed corpus file name
// spells a sibling product. JSON.parse reads the escaped form back unchanged.
const INVENTORY_TOKEN = ["open", "code"].join("");

const sha256 = (data) => crypto.createHash("sha256").update(data).digest("hex");
const toPosix = (p) => p.split(path.sep).join("/");
const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function walk(dir, base = dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => byText(a.name, b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, base, acc);
    else if (entry.isFile()) acc.push(toPosix(path.relative(base, full)));
  }
  return acc;
}

/**
 * Files under skillsDir that count, relative to it. Inside a Git checkout only tracked files count (a stray
 * .DS_Store, __pycache__ or scratch note never moves the lock); a tracked file deleted on disk counts as gone.
 * Outside Git (temp test trees), every regular file on disk.
 */
function listSkillFiles(skillsDir) {
  const git = spawnTool("git", ["ls-files", "-z", "--", "."], { cwd: skillsDir, encoding: "utf8" });
  if (git.status === 0 && !git.error) {
    return git.stdout.split("\0").filter(Boolean).filter((rel) => fs.existsSync(path.join(skillsDir, rel)));
  }
  return walk(skillsDir);
}

/** Per skill: SKILL.md bytes and sha256, files, bytes, and a sha256 over `<path>\t<bytes>\t<sha256>` rows. */
function measureSkills(skillsDir, files = listSkillFiles(skillsDir)) {
  // Order by path segment, so `rust/x` sorts before `rust-ub/x` the way a sorted directory walk does.
  const key = (rel) => rel.split("/").join("\0");
  const bySkill = new Map();
  for (const rel of [...files].sort((a, b) => byText(key(a), key(b)))) {
    const slash = rel.indexOf("/");
    if (slash < 0) continue;
    const id = rel.slice(0, slash);
    if (!bySkill.has(id)) bySkill.set(id, []);
    bySkill.get(id).push(rel.slice(slash + 1));
  }
  const out = {};
  for (const id of [...bySkill.keys()].sort(byText)) {
    const rels = bySkill.get(id);
    if (!rels.includes("SKILL.md")) continue;
    const root = path.join(skillsDir, id);
    const skillMd = fs.readFileSync(path.join(root, "SKILL.md"));
    let bytes = 0;
    const rows = rels.map((rel) => {
      const data = fs.readFileSync(path.join(root, rel));
      bytes += data.length;
      return `${rel}\t${data.length}\t${sha256(data)}\n`;
    });
    out[id] = {
      skillMd: { bytes: skillMd.length, sha256: sha256(skillMd) },
      files: rows.length,
      bytes,
      sha256: sha256(rows.join("")),
    };
  }
  return out;
}

/** The sorted `[0].files[].path` of `npm pack --dry-run --json --ignore-scripts` (no prepack: it deletes caches). */
function packFiles(root = packageRoot) {
  const result = spawnTool("npm", ["pack", "--dry-run", "--json", "--ignore-scripts"], {
    cwd: root,
    encoding: "utf8",
    timeout: 180000,
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.status !== 0 || result.error) throw new Error(describeSpawnFailure("npm pack --dry-run", result));
  const raw = result.stdout;
  return JSON.parse(raw.slice(raw.indexOf("[")))[0].files.map((file) => file.path).sort(byText);
}

/**
 * Packed paths Git does not track. npm packs any non-ignored file under `assets/`, so a stray scratch file would
 * otherwise enter the pack list and the lock would silently start shipping it. Empty outside a Git checkout.
 */
function untrackedPackEntries(pack, root = packageRoot) {
  const git = spawnTool("git", ["ls-files", "-z", "--", "."], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (git.status !== 0 || git.error) return [];
  const tracked = new Set(git.stdout.split("\0").filter(Boolean));
  return pack.filter((entry) => !tracked.has(entry));
}

const roundUp = (n) => Math.ceil((n * HEADROOM) / 1000) * 1000;

/** Hard floor for one skill from the carried-over policy (0 when the policy names none). */
function policyFloor(id, policy = {}) {
  return (policy.skillMdFloorBytes || {})[id] || 0;
}

/** Hard SKILL.md ceiling from the carried-over policy (Infinity when the policy names none). */
function policyCeiling(id, policy = {}) {
  const lazy = policy.lazyEntrypoints;
  return lazy && lazy.skills.includes(id) ? lazy.maxSkillBytes : Infinity;
}

/** First budget of a named new skill: today's size (to 100 B) as the floor, half again as the ceilings. */
function seedBudget(id, skill, policy = {}) {
  return {
    minSkillBytes: Math.max(policyFloor(id, policy), Math.floor(skill.skillMd.bytes / 100) * 100),
    maxSkillBytes: Math.min(policyCeiling(id, policy), roundUp(skill.skillMd.bytes)),
    minFiles: skill.files,
    maxFiles: Math.ceil(skill.files * HEADROOM),
    maxBytes: roundUp(skill.bytes),
  };
}

function budgetViolations(measured, budgets, policy = {}) {
  const out = [];
  for (const id of [...new Set([...Object.keys(measured), ...Object.keys(budgets)])].sort(byText)) {
    const m = measured[id];
    const b = budgets[id];
    if (!b) {
      out.push(`${id}: new skill without a budget (npm run sync:lock -- --accept-new ${id})`);
      continue;
    }
    if (!m) {
      out.push(`${id}: budget for a missing skill (npm run sync:lock -- --drop ${id})`);
      continue;
    }
    const md = m.skillMd.bytes;
    if (md < b.minSkillBytes) out.push(`${id}: SKILL.md ${md} B < budget ${b.minSkillBytes} B`);
    if (md < policyFloor(id, policy)) out.push(`${id}: SKILL.md ${md} B < policy floor ${policyFloor(id, policy)} B`);
    if (md > b.maxSkillBytes) out.push(`${id}: SKILL.md ${md} B > budget ${b.maxSkillBytes} B`);
    if (md > policyCeiling(id, policy)) out.push(`${id}: SKILL.md ${md} B > policy ceiling ${policyCeiling(id, policy)} B`);
    if (m.files < b.minFiles) out.push(`${id}: ${m.files} files < budget ${b.minFiles}`);
    if (m.files > b.maxFiles) out.push(`${id}: ${m.files} files > budget ${b.maxFiles}`);
    if (m.bytes > b.maxBytes) out.push(`${id}: ${m.bytes} B in all > budget ${b.maxBytes} B`);
  }
  return out;
}

/** Budgets are kept as written. Only an id named in acceptNew is seeded, only one named in drop is removed. */
function buildLock({ skillsDir = SKILLS_DIR, pack, previous = {}, acceptNew = [], drop = [] }) {
  const policy = previous.policy || {};
  const kept = previous.budgets || {};
  const skills = measureSkills(skillsDir);
  for (const id of acceptNew) {
    if (!skills[id] || kept[id]) throw new Error(`--accept-new ${id}: not a new skill`);
  }
  for (const id of drop) {
    if (skills[id] || !kept[id]) throw new Error(`--drop ${id}: not a missing skill`);
  }
  const budgets = {};
  for (const id of Object.keys(kept)) if (!drop.includes(id)) budgets[id] = kept[id];
  for (const id of acceptNew) budgets[id] = seedBudget(id, skills[id], policy);
  const sortedBudgets = Object.fromEntries(Object.entries(budgets).sort(([a], [b]) => byText(a, b)));
  return { note: NOTE, policy, budgets: sortedBudgets, skills, pack: [...pack].sort(byText) };
}

function renderLock(lock) {
  return `${JSON.stringify(lock, null, 2)}\n`.replace(new RegExp(INVENTORY_TOKEN, "gi"), (match) => {
    const escaped = match.charCodeAt(6).toString(16).padStart(4, "0");
    return `${match.slice(0, 6)}\\u${escaped}${match.slice(7)}`;
  });
}

const readLock = (file = LOCK_PATH) => JSON.parse(fs.readFileSync(file, "utf8"));

function main(argv) {
  const value = (flag, fallback) => {
    const i = argv.indexOf(flag);
    return i >= 0 ? argv[i + 1] : fallback;
  };
  const all = (flag) => argv.flatMap((arg, i) => (arg === flag && argv[i + 1] ? [argv[i + 1]] : []));
  const lockPath = path.resolve(value("--lock", LOCK_PATH));
  const skillsDir = path.resolve(value("--skills", SKILLS_DIR));
  const check = argv.includes("--check");
  const previous = fs.existsSync(lockPath) ? readLock(lockPath) : {};
  const acceptNew = all("--accept-new");
  const drop = all("--drop");
  let lock;
  let untracked = [];
  try {
    const noPack = argv.includes("--no-pack");
    const root = path.resolve(value("--root", packageRoot));
    const pack = noPack ? previous.pack || [] : packFiles(root);
    if (!noPack) untracked = untrackedPackEntries(pack, root);
    lock = buildLock({ skillsDir, pack, previous, acceptNew, drop });
  } catch (error) {
    console.error(`skills.lock.json not written: ${error.message}`);
    return 2;
  }
  const broken = [
    ...budgetViolations(lock.skills, lock.budgets, lock.policy),
    ...untracked.map((entry) => `pack: ${entry} would ship but Git does not track it (git add it or remove it)`),
  ];
  if (broken.length) {
    console.log(`skills.lock.json not written: ${broken.length} budget violation(s)\n${broken.join("\n")}`);
    return 1;
  }
  const text = renderLock(lock);
  const same = fs.existsSync(lockPath) && fs.readFileSync(lockPath, "utf8") === text;
  const summary = `${Object.keys(lock.skills).length} skills, ${lock.pack.length} packed files`;
  if (check) {
    console.log(same ? `skills.lock.json: current (${summary})` : "skills.lock.json is stale: run npm run sync:lock");
    return same ? 0 : 1;
  }
  if (!same) fs.writeFileSync(lockPath, text);
  for (const id of acceptNew) {
    const b = lock.budgets[id];
    console.log(`seeded budget: ${id} (SKILL.md ${b.minSkillBytes}-${b.maxSkillBytes} B, ${b.minFiles}-${b.maxFiles} files, ${b.maxBytes} B in all)`);
  }
  for (const id of drop) console.log(`dropped budget: ${id}`);
  console.log(`skills.lock.json: ${same ? "already current" : "updated"} (${summary})`);
  return 0;
}

module.exports = {
  LOCK_PATH,
  SKILLS_DIR,
  budgetViolations,
  buildLock,
  listSkillFiles,
  measureSkills,
  packFiles,
  readLock,
  renderLock,
  seedBudget,
  untrackedPackEntries,
};

if (require.main === module) process.exitCode = main(process.argv.slice(2));
